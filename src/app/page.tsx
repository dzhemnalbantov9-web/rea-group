function Gallery({
  product,
  language,
  onClose,
}: {
  product: Product;
  language: SiteLanguage;
  onClose: () => void;
}) {
  const [index, setIndex] = useState(0);
  const photoCount = product.photos.length;

  useEffect(() => {
    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    function handleKey(event: KeyboardEvent) {
      if (event.key === "Escape") {
        onClose();
      }

      if (photoCount > 0 && event.key === "ArrowRight") {
        setIndex((current) => (current + 1) % photoCount);
      }

      if (photoCount > 0 && event.key === "ArrowLeft") {
        setIndex(
          (current) => (current - 1 + photoCount) % photoCount
        );
      }
    }

    window.addEventListener("keydown", handleKey);

    return () => {
      document.body.style.overflow = previousOverflow;
      window.removeEventListener("keydown", handleKey);
    };
  }, [onClose, photoCount]);

  function previous() {
    if (photoCount > 0) {
      setIndex((current) => (current - 1 + photoCount) % photoCount);
    }
  }

  function next() {
    if (photoCount > 0) {
      setIndex((current) => (current + 1) % photoCount);
    }
  }

  return (
    <div className="gallery-backdrop" onClick={onClose}>
      <div
        className="gallery-panel"
        role="dialog"
        aria-modal="true"
        aria-label={`Галерия: ${tr(product.name, language)}`}
        onClick={(event) => event.stopPropagation()}
      >
        <div className="gallery-heading">
          <div>
            <span className="overline">{tr("TACH / ПРОДУКТОВА ГАЛЕРИЯ", language)}</span>
            <h2>{tr(product.name, language)}</h2>
          </div>

          <button
            type="button"
            className="gallery-close"
            onClick={onClose}
            aria-label="Затвори"
          >
            ✕
          </button>
        </div>

        {photoCount > 0 ? (
          <>
            <div className="gallery-main">
              <img
                src={product.photos[index]}
                alt={`${tr(product.name, language)} — снимка ${index + 1}`}
              />
            </div>

            <div className="gallery-controls">
              <button type="button" onClick={previous}>{tr("← Предишна", language)}</button>

              <span>
                {index + 1} / {photoCount}
              </span>

              <button type="button" onClick={next}>{tr("Следваща →", language)}</button>
            </div>

            <div className="gallery-thumbnails">
              {product.photos.map((photo, photoIndex) => (
                <button
                  type="button"
                  key={`${photo}-${photoIndex}`}
                  className={index === photoIndex ? "active" : ""}
                  onClick={() => setIndex(photoIndex)}
                  aria-label={`Покажи снимка ${photoIndex + 1}`}
                >
                  <img src={photo} alt="" />
                </button>
              ))}
            </div>
          </>
        ) : (
          <div className="no-results">{tr("За този продукт все още няма добавени снимки.", language)}</div>
        )}
      </div>
    </div>
  );
}

